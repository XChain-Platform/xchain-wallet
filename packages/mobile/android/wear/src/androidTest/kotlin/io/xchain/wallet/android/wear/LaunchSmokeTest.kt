package io.xchain.wallet.android.wear

import androidx.compose.ui.test.assertIsDisplayed
import androidx.compose.ui.test.junit4.v2.createAndroidComposeRule
import androidx.compose.ui.test.onNodeWithText
import androidx.compose.ui.test.onRoot
import androidx.test.ext.junit.runners.AndroidJUnit4
import org.junit.Rule
import org.junit.Test
import org.junit.runner.RunWith

@RunWith(AndroidJUnit4::class)
class LaunchSmokeTest {
    @get:Rule
    val compose = createAndroidComposeRule<MainActivity>()

    @Test
    fun launchWithoutPhoneSurvivesBezelRotation() {
        val prompt = compose.onNodeWithText("Open XChain Wallet on your phone")

        prompt.assertIsDisplayed()
        compose.onRoot().rotateBezel(72f)
        prompt.assertIsDisplayed()
    }
}
