// Sync the wallet's bundled chain descriptors (the authoritative UX/endpoint
// metadata per chain, packages/core/src/registry/descriptors/) into the hub's
// served chain-registry snapshot (xchain-hub/src/chain-registry.json, the
// GET /api/v1/chain-registry payload). Same canonical->vendored pattern as
// xchain-hub/bin/sync-coins.sh, with JSON as the wire shape: the hub must not
// grow its own copy of wallet UX metadata, and the wallet must not fetch a
// registry that disagrees with what it ships.
//
// The snapshot is only rewritten when the descriptors actually change, so
// generated_at stays stable and --check can byte-compare descriptor content.
//
// TWO GUARDS LIVE HERE, because the cross-repo copy failed silently
// once: wallet b3fd8dd5 corrected the bitcoin-regtest encoder port and the hub
// snapshot kept the superseded value on origin for both repos, since the only
// thing comparing them was a hub test that SKIPS when the wallet sibling is not
// checked out.
//
//   1. A wallet-side fingerprint (bin/chain-registry.sync.json) records the
//      digest of the descriptors as of the last sync. It is committed with the
//      descriptor edit, so test/unit/chainRegistrySync.test.js can fail a
//      descriptor change that was never mirrored WITHOUT any sibling checkout.
//      A digest rather than a vendored copy of the snapshot: the wallet is the
//      source, so a second copy of its own descriptors inside the same repo
//      would be noise, and the diff is one command away either way.
//
//   2. A write refuses to run from a checkout whose origin carries descriptor
//      commits this tree does not have. The generator reads the LOCAL tree, so
//      a stale clone rewrites the superseded value back into the hub and it
//      looks like a legitimate resync. That is the trap, not the drift.
//
// Usage:
//   node bin/sync-chain-registry.mjs                Write/refresh the snapshot + fingerprint.
//   node bin/sync-chain-registry.mjs --check        Exit 1 if either has drifted.
//   node bin/sync-chain-registry.mjs --allow-stale  Sync anyway from a stale checkout.
//   node bin/sync-chain-registry.mjs --no-fetch     Do not refresh the upstream ref first.
//
// Exit codes: 0 in sync · 1 drift or a failed write · 2 refused (stale checkout).

import { createHash } from 'crypto';
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';
import { BUNDLED_DESCRIPTORS } from '../packages/core/src/registry/descriptors/index.js';
import { checkoutFreshness, stalenessMessage } from './lib/checkout-freshness.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const WALLET_ROOT = path.resolve(HERE, '..');
const OUT = path.resolve(HERE, '../../xchain-hub/src/chain-registry.json');
const FINGERPRINT = path.resolve(HERE, 'chain-registry.sync.json');

// Repo-relative, because they are handed to `git rev-list -- <pathspec>`.
const DESCRIPTOR_PATHS = [
    'packages/core/src/registry/descriptors',
    'bin/chain-registry.sync.json',
];

const CHECK = process.argv.includes('--check');
const ALLOW_STALE = process.argv.includes('--allow-stale');
const FETCH = !process.argv.includes('--no-fetch');
const SCHEMA_VERSION = 1;

const nextDescriptors = JSON.parse(JSON.stringify(BUNDLED_DESCRIPTORS));
// The exact string the hub test byte-compares, so one digest speaks for both
// artifacts and neither can drift from the other's idea of the payload.
const canonical = JSON.stringify(nextDescriptors);
const digest = createHash('sha256').update(canonical).digest('hex');

const snapshotJson = (generatedAt) => JSON.stringify({
    schema_version: SCHEMA_VERSION,
    generated_at:   generatedAt,
    descriptors:    nextDescriptors
}, null, 2) + '\n';

const fingerprintJson = (syncedAt) => JSON.stringify({
    _comment: 'Generated by xchain-wallet/bin/sync-chain-registry.mjs. Records the '
        + 'descriptors mirrored into xchain-hub/src/chain-registry.json, so a '
        + 'descriptor change that was never mirrored fails in THIS repo, with no '
        + 'hub checkout present. Do not hand-edit: rerun the script.',
    schema_version:     SCHEMA_VERSION,
    descriptor_count:   nextDescriptors.length,
    descriptors_sha256: digest,
    hub_snapshot:       'xchain-hub/src/chain-registry.json',
    synced_at:          syncedAt
}, null, 2) + '\n';

/** Parse a JSON file, or null when it is absent or unreadable. */
function readJson(file) {
    if (!existsSync(file)) return null;
    try { return JSON.parse(readFileSync(file, 'utf8')); } catch { return null; }
}

const snapshot = readJson(OUT);
const hubPresent = existsSync(path.dirname(OUT));
const snapshotInSync = Boolean(snapshot)
    && snapshot.schema_version === SCHEMA_VERSION
    && JSON.stringify(snapshot.descriptors) === canonical;

const fingerprint = readJson(FINGERPRINT);
const fingerprintInSync = Boolean(fingerprint)
    && fingerprint.schema_version === SCHEMA_VERSION
    && fingerprint.descriptors_sha256 === digest;

/**
 * Say, on the error stream, whether a stale checkout explains what we just
 * found. Only called once something is already wrong: a drift report that
 * sends you to rerun the generator is actively harmful when the generator
 * would write your stale values into the hub.
 */
function explainIfStale() {
    const fresh = checkoutFreshness({ repoRoot: WALLET_ROOT, paths: DESCRIPTOR_PATHS, fetch: false });
    const msg = stalenessMessage(fresh, 'this wallet checkout');
    if (!msg) return;
    console.error('NOTE: ' + msg + '.');
    console.error('      Pull first. Resyncing from here would write this tree\'s superseded '
        + 'descriptors into the hub.');
}

if (CHECK) {
    let ok = true;

    if (!fingerprintInSync) {
        ok = false;
        console.error(fingerprint
            ? 'DRIFT: bin/chain-registry.sync.json does not match the bundled descriptors; the '
                + 'hub snapshot was never resynced for the current descriptors.'
            : 'DRIFT: bin/chain-registry.sync.json is missing or unreadable; run '
                + 'xchain-wallet/bin/sync-chain-registry.mjs.');
    }

    // The hub half is a bonus, not the gate: it runs only in a tree that has
    // the sibling (the monorepo, bin/ci-all.sh). Its absence is stated rather
    // than silently skipped, so a run that proved less than it looks like it
    // proved says so.
    if (!hubPresent) {
        console.log('NOTE: no xchain-hub checkout beside this one; checked the wallet fingerprint only.');
    } else if (!snapshotInSync) {
        ok = false;
        console.error('DRIFT: xchain-hub/src/chain-registry.json does not match the wallet bundled '
            + 'descriptors.');
    }

    if (ok) {
        console.log('OK: chain-registry fingerprint'
            + (hubPresent ? ' and hub snapshot match' : ' matches')
            + ' the wallet bundled descriptors.');
        process.exit(0);
    }
    explainIfStale();
    console.error('Fix: run xchain-wallet/bin/sync-chain-registry.mjs and commit both files.');
    process.exit(1);
}

// ---- write path -------------------------------------------------------------

if (!ALLOW_STALE) {
    const fresh = checkoutFreshness({ repoRoot: WALLET_ROOT, paths: DESCRIPTOR_PATHS, fetch: FETCH });
    if (fresh.answerable && fresh.behind > 0) {
        console.error('REFUSED: ' + stalenessMessage(fresh, 'this wallet checkout') + '.');
        console.error('This script copies the LOCAL descriptors into the hub, so syncing from here '
            + 'would rewrite a superseded value and look like a legitimate resync.');
        console.error('Pull, then rerun. Use --allow-stale only when you mean to publish THIS '
            + 'tree\'s descriptors.');
        process.exit(2);
    }
    if (!fresh.answerable && fresh.reason)
        console.log('NOTE: freshness unchecked (' + fresh.reason + ').');
}

if (!hubPresent) {
    console.error('ERROR: no xchain-hub checkout at ' + path.dirname(OUT) + '; the snapshot cannot '
        + 'be written. Check the sibling out beside this repo, or run --check to verify the '
        + 'wallet fingerprint alone.');
    process.exit(1);
}

const wrote = [];
if (!snapshotInSync) {
    writeFileSync(OUT, snapshotJson(new Date().toISOString()));
    wrote.push(OUT);
}
if (!fingerprintInSync) {
    writeFileSync(FINGERPRINT, fingerprintJson(new Date().toISOString()));
    wrote.push(FINGERPRINT);
}

if (!wrote.length) {
    console.log('chain-registry already in sync (' + nextDescriptors.length
        + ' descriptors); nothing rewritten.');
    process.exit(0);
}
for (const file of wrote) console.log('wrote ' + file);
console.log(nextDescriptors.length + ' descriptors, schema_version ' + SCHEMA_VERSION
    + ', sha256 ' + digest.slice(0, 12) + '. Commit the hub snapshot AND the wallet fingerprint.');
